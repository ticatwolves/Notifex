// Package store is the persistence boundary. Services and transports depend on
// these interfaces and plain types only; they never import ent.
//
// Tenancy rules:
//   - every method on tenant-owned data takes the TenantID explicitly;
//   - reading another tenant's row returns ErrNotFound (never ErrForbidden), so
//     existence does not leak;
//   - the implementation also enforces scoping in ent hooks/interceptors, so a
//     forgotten predicate fails closed (see internal/store/tenantscope).
package store

import (
	"context"
	"errors"
	"time"

	"github.com/google/uuid"

	"github.com/sbshobhit/notifex/internal/crypto"
)

// Errors returned by Store implementations. Match with errors.Is.
var (
	// ErrNotFound: the row does not exist in this tenant (or at all).
	ErrNotFound = errors.New("store: not found")
	// ErrConflict: a uniqueness constraint was violated, or a row is still
	// referenced and cannot be deleted.
	ErrConflict = errors.New("store: conflict")
	// ErrInvalid: input failed validation before reaching the database.
	ErrInvalid = errors.New("store: invalid input")
)

// TenantID identifies a tenant. It is a distinct type so an application or
// user id can't be passed where a tenant id belongs.
type TenantID uuid.UUID

// NewTenantID returns a fresh UUIDv7 tenant id.
func NewTenantID() TenantID { return TenantID(uuid.Must(uuid.NewV7())) }

// UUID returns the underlying uuid.
func (t TenantID) UUID() uuid.UUID { return uuid.UUID(t) }

// String implements fmt.Stringer.
func (t TenantID) String() string { return uuid.UUID(t).String() }

// Store is the root persistence interface.
type Store interface {
	Tenants() TenantStore
	Users() UserStore
	Memberships() MembershipStore
	Applications() ApplicationStore
	Environments() EnvironmentStore
	APIKeys() APIKeyStore
	Audit() AuditStore
	// WithTx runs fn in one transaction. The Store passed to fn is bound to it,
	// so a mutation and its audit event commit or roll back together. fn's
	// error rolls back; a panic rolls back and re-panics.
	WithTx(ctx context.Context, fn func(ctx context.Context, tx Store) error) error
}

// Page requests a page of results in id order (ids are UUIDv7, so this is
// creation order). After is the last id of the previous page.
type Page struct {
	Limit int
	After uuid.UUID
}

// Page size bounds. Unbounded queries are not offered.
const (
	DefaultPageSize = 50
	MaxPageSize     = 200
)

// Normalize clamps Limit into [1, MaxPageSize].
func (p Page) Normalize() Page {
	switch {
	case p.Limit <= 0:
		p.Limit = DefaultPageSize
	case p.Limit > MaxPageSize:
		p.Limit = MaxPageSize
	}
	return p
}

// ---- tenants ----

// TenantStatus is the lifecycle state of a tenant.
type TenantStatus string

// Tenant statuses.
const (
	TenantActive    TenantStatus = "active"
	TenantSuspended TenantStatus = "suspended"
	TenantDeleted   TenantStatus = "deleted"
)

// Tenant is a customer organisation. The wrapped DEK is never exposed here;
// use TenantStore.WrappedDEK.
type Tenant struct {
	ID                    TenantID
	Name                  string
	Slug                  string
	Status                TenantStatus
	Plan                  string
	Quotas                map[string]int64
	PlatformSMSDailyLimit int
	Sandbox               bool
	DEKShredded           bool
	CreatedAt, UpdatedAt  time.Time
}

// NewTenant is the input to TenantStore.Create. The caller generates the id
// first (NewTenantID) because the DEK's encryption context binds it to the
// tenant id; the DEK is generated by the caller (KeyProvider) so the store
// never sees plaintext key material.
type NewTenant struct {
	ID                    TenantID
	Name                  string
	Slug                  string
	Plan                  string
	PlatformSMSDailyLimit int
	DEK                   crypto.WrappedDEK
	// No Sandbox field: new tenants always start sandboxed; lifting it is a
	// platform-operator action (TenantPatch.Sandbox).
}

// TenantPatch updates selected fields; nil means unchanged.
type TenantPatch struct {
	Name                  *string
	Status                *TenantStatus
	Plan                  *string
	Quotas                map[string]int64 // nil = unchanged; empty map clears
	PlatformSMSDailyLimit *int
	Sandbox               *bool
}

// TenantStore manages tenants. These are platform-level operations: callers
// are the signup flow, the platform operator and system jobs.
type TenantStore interface {
	Create(ctx context.Context, in NewTenant) (Tenant, error)
	Get(ctx context.Context, id TenantID) (Tenant, error)
	GetBySlug(ctx context.Context, slug string) (Tenant, error)
	Update(ctx context.Context, id TenantID, p TenantPatch) (Tenant, error)
	// WrappedDEK implements crypto.DEKSource. It returns
	// crypto.ErrDataKeyDestroyed after ShredDEK.
	WrappedDEK(ctx context.Context, id uuid.UUID) (crypto.WrappedDEK, error)
	// ShredDEK deletes the tenant's wrapped DEK, making all of its encrypted
	// data unreadable. Irreversible.
	ShredDEK(ctx context.Context, id TenantID) error
}

// ---- users ----

// UserStatus is the state of a console user.
type UserStatus string

// User statuses.
const (
	UserActive   UserStatus = "active"
	UserDisabled UserStatus = "disabled"
)

// User is a console user (global, not tenant-owned).
type User struct {
	ID              uuid.UUID
	Email           string
	Name            string
	PasswordHash    *string
	Status          UserStatus
	EmailVerifiedAt *time.Time
	CreatedAt       time.Time
	UpdatedAt       time.Time
}

// NewUser is the input to UserStore.Create.
type NewUser struct {
	Email        string
	Name         string
	PasswordHash *string
}

// UserStore manages console users. Emails are compared case-insensitively
// (stored lower-cased).
type UserStore interface {
	Create(ctx context.Context, in NewUser) (User, error)
	Get(ctx context.Context, id uuid.UUID) (User, error)
	GetByEmail(ctx context.Context, email string) (User, error)
}

// ---- memberships ----

// Role is a tenant console role (docs/03 permissions matrix).
type Role string

// Roles.
const (
	RoleOwner     Role = "owner"
	RoleAdmin     Role = "admin"
	RoleDeveloper Role = "developer"
	RoleViewer    Role = "viewer"
)

// Membership links a user to a tenant.
type Membership struct {
	ID        uuid.UUID
	TenantID  TenantID
	UserID    uuid.UUID
	Role      Role
	CreatedAt time.Time
	UpdatedAt time.Time
}

// MembershipStore manages tenant memberships. Business rules (last owner,
// admins can't demote owners) live in the service layer.
type MembershipStore interface {
	Create(ctx context.Context, tid TenantID, userID uuid.UUID, role Role) (Membership, error)
	Get(ctx context.Context, tid TenantID, userID uuid.UUID) (Membership, error)
	List(ctx context.Context, tid TenantID, p Page) ([]Membership, error)
	UpdateRole(ctx context.Context, tid TenantID, userID uuid.UUID, role Role) (Membership, error)
	Delete(ctx context.Context, tid TenantID, userID uuid.UUID) error
	// ListForUser returns the user's memberships across tenants (tenant
	// switcher). Scoped by user, not tenant.
	ListForUser(ctx context.Context, userID uuid.UUID) ([]Membership, error)
}

// ---- applications ----

// Application groups workflows, environments and keys.
type Application struct {
	ID          uuid.UUID
	TenantID    TenantID
	Name        string
	Key         string
	Description string
	CreatedAt   time.Time
	UpdatedAt   time.Time
}

// NewApplication is the input to ApplicationStore.Create.
type NewApplication struct {
	Name        string
	Key         string
	Description string
}

// ApplicationPatch updates selected fields; nil means unchanged.
type ApplicationPatch struct {
	Name        *string
	Description *string
}

// ApplicationStore manages applications.
type ApplicationStore interface {
	Create(ctx context.Context, tid TenantID, in NewApplication) (Application, error)
	Get(ctx context.Context, tid TenantID, id uuid.UUID) (Application, error)
	List(ctx context.Context, tid TenantID, p Page) ([]Application, error)
	Update(ctx context.Context, tid TenantID, id uuid.UUID, p ApplicationPatch) (Application, error)
	// Delete fails with ErrConflict while environments or keys reference it.
	Delete(ctx context.Context, tid TenantID, id uuid.UUID) error
}

// ---- environments ----

// EnvironmentName is a deployment stage.
type EnvironmentName string

// Environment names.
const (
	EnvDev     EnvironmentName = "dev"
	EnvStaging EnvironmentName = "staging"
	EnvProd    EnvironmentName = "prod"
)

// Environment is a stage of an application.
type Environment struct {
	ID            uuid.UUID
	TenantID      TenantID
	ApplicationID uuid.UUID
	Name          EnvironmentName
	CreatedAt     time.Time
	UpdatedAt     time.Time
}

// EnvironmentStore manages environments.
type EnvironmentStore interface {
	// Create returns ErrNotFound if the application is not in this tenant.
	Create(ctx context.Context, tid TenantID, appID uuid.UUID, name EnvironmentName) (Environment, error)
	Get(ctx context.Context, tid TenantID, id uuid.UUID) (Environment, error)
	List(ctx context.Context, tid TenantID, appID uuid.UUID) ([]Environment, error)
	// Delete fails with ErrConflict while API keys reference it.
	Delete(ctx context.Context, tid TenantID, id uuid.UUID) error
}

// ---- API keys ----

// APIKey is a stored API key. Hash is HMAC-SHA256(pepper, secret).
type APIKey struct {
	ID            uuid.UUID
	TenantID      TenantID
	ApplicationID uuid.UUID
	EnvironmentID uuid.UUID
	Name          string
	Prefix        string
	Hash          []byte
	Scopes        []string
	ExpiresAt     *time.Time
	LastUsedAt    *time.Time
	RevokedAt     *time.Time
	CreatedAt     time.Time
	UpdatedAt     time.Time
}

// NewAPIKey is the input to APIKeyStore.Create.
type NewAPIKey struct {
	ApplicationID uuid.UUID
	EnvironmentID uuid.UUID
	Name          string
	Prefix        string
	Hash          []byte
	Scopes        []string
	ExpiresAt     *time.Time
}

// APIKeyStore manages API keys.
type APIKeyStore interface {
	// Create returns ErrNotFound if the environment is not in this tenant and
	// application.
	Create(ctx context.Context, tid TenantID, in NewAPIKey) (APIKey, error)
	// GetByPrefix is the one unscoped lookup: the key is what identifies the
	// tenant. Callers must verify the hash, revocation and expiry.
	GetByPrefix(ctx context.Context, prefix string) (APIKey, error)
	List(ctx context.Context, tid TenantID, appID uuid.UUID, p Page) ([]APIKey, error)
	// Revoke is idempotent: revoking a revoked key keeps the first timestamp.
	Revoke(ctx context.Context, tid TenantID, id uuid.UUID, at time.Time) error
	TouchLastUsed(ctx context.Context, tid TenantID, id uuid.UUID, at time.Time) error
}

// ---- audit ----

// ActorType says who performed an action.
type ActorType string

// Actor types.
const (
	ActorUser     ActorType = "user"
	ActorAPIKey   ActorType = "api_key"
	ActorOperator ActorType = "operator"
	ActorSystem   ActorType = "system"
)

// AuditEvent records a control-plane mutation. Before/After must already be
// redacted (no secrets, no PII).
type AuditEvent struct {
	ID         uuid.UUID
	TenantID   *TenantID // nil for platform-level events
	ActorType  ActorType
	ActorID    string
	Action     string // e.g. "application.create"
	EntityType string
	EntityID   string
	Before     map[string]any
	After      map[string]any
	RequestID  string
	CreatedAt  time.Time
}

// AuditStore appends and lists audit events. There is no update or delete.
type AuditStore interface {
	Append(ctx context.Context, e AuditEvent) (AuditEvent, error)
	// List returns a tenant's events, newest first.
	List(ctx context.Context, tid TenantID, p Page) ([]AuditEvent, error)
}

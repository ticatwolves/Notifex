// Membership links a user to a tenant.
type Membership struct {
	ID        uuid.UUID
	TenantID  TenantID
	UserID    uuid.UUID
	Role      Role
	CreatedAt time.Time
	UpdatedAt time.Time
}

// MembershipStore manages tenant memberships. Business rules (last owner,
// admins can't demote owners) live in the service layer.
type MembershipStore interface {
	Create(ctx context.Context, tid TenantID, userID uuid.UUID, role Role) (Membership, error)
	Get(ctx context.Context, tid TenantID, userID uuid.UUID) (Membership, error)
	List(ctx context.Context, tid TenantID, p Page) ([]Membership, error)
	UpdateRole(ctx context.Context, tid TenantID, userID uuid.UUID, role Role) (Membership, error)
	Delete(ctx context.Context, tid TenantID, userID uuid.UUID) error
	// ListForUser returns the user's memberships across tenants (tenant
	// switcher). Scoped by user, not tenant.
	ListForUser(ctx context.Context, userID uuid.UUID) ([]Membership, error)
	// LockOwners locks the tenant's owner memberships until the transaction
	// ends and returns their user ids. Every change that could remove an
	// owner takes this lock first, so the last owner can't be removed by
	// two concurrent requests. Use inside WithTx.
	LockOwners(ctx context.Context, tid TenantID) ([]uuid.UUID, error)
	// CountOwnedBy counts tenants (not deleted) where userID is an owner.
	CountOwnedBy(ctx context.Context, userID uuid.UUID) (int, error)
}

